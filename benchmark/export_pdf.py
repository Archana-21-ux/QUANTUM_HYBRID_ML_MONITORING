"""Export the Phase 4 benchmark report as a PDF.

Renders the frozen benchmark artifacts (results.csv, ablation_results.csv,
INTERPRETATION.md, per-scenario plots) into benchmark/REPORT.pdf using
matplotlib — no extra dependencies.

Usage: uv run python benchmark/export_pdf.py
"""

from __future__ import annotations

import textwrap
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.image as mpimg
import matplotlib.pyplot as plt
import pandas as pd
from matplotlib.backends.backend_pdf import PdfPages

from quantumguard.config import load_config

BENCH_DIR = Path(__file__).parent
OUT_PATH = BENCH_DIR / "REPORT.pdf"
PAGE_SIZE = (8.27, 11.69)  # A4 portrait, inches


def _text_page(pdf: PdfPages, title: str, body: str, font_size: int = 9) -> None:
    fig = plt.figure(figsize=PAGE_SIZE)
    fig.text(0.08, 0.94, title, fontsize=15, fontweight="bold")
    wrapped = []
    for paragraph in body.split("\n"):
        wrapped.extend(textwrap.wrap(paragraph, width=95) or [""])
    fig.text(0.08, 0.90, "\n".join(wrapped), fontsize=font_size, va="top", family="serif")
    pdf.savefig(fig)
    plt.close(fig)


def _table_page(pdf: PdfPages, title: str, frame: pd.DataFrame, note: str = "") -> None:
    fig, ax = plt.subplots(figsize=PAGE_SIZE)
    ax.axis("off")
    fig.text(0.08, 0.94, title, fontsize=15, fontweight="bold")
    if note:
        fig.text(0.08, 0.915, note, fontsize=8, style="italic")

    display = frame.fillna("—").astype(str)
    table = ax.table(
        cellText=display.values,
        colLabels=display.columns,
        loc="upper center",
        cellLoc="center",
    )
    table.auto_set_font_size(False)
    table.set_fontsize(7)
    table.scale(1.0, 1.35)
    for (row, _), cell in table.get_celld().items():
        cell.set_edgecolor("#cccccc")
        if row == 0:
            cell.set_facecolor("#e8edf5")
            cell.set_text_props(fontweight="bold")
    pdf.savefig(fig)
    plt.close(fig)


def _image_page(pdf: PdfPages, title: str, image_path: Path) -> None:
    fig = plt.figure(figsize=PAGE_SIZE)
    fig.text(0.08, 0.94, title, fontsize=13, fontweight="bold")
    ax = fig.add_axes([0.05, 0.25, 0.9, 0.62])
    ax.axis("off")
    ax.imshow(mpimg.imread(image_path))
    pdf.savefig(fig)
    plt.close(fig)


def main() -> None:
    cfg = load_config()
    results = pd.read_csv(BENCH_DIR / "results.csv")
    ablation = pd.read_csv(BENCH_DIR / "ablation_results.csv")
    interpretation = (BENCH_DIR / "INTERPRETATION.md").read_text(encoding="utf-8")

    with PdfPages(OUT_PATH) as pdf:
        # cover
        held_out = ", ".join(cfg.benchmark.held_out_scenarios)
        evaluation = ", ".join(cfg.benchmark.evaluation_scenarios)
        _text_page(
            pdf,
            "QuantumGuard — drift detector benchmark report",
            "Hybrid classical / quantum-inspired drift monitoring for a production "
            "fraud-detection model.\n\n"
            f"Held-out scenarios (calibration + feature-map selection): {held_out}\n"
            f"Evaluation scenarios (final numbers, disjoint — asserted): {evaluation}\n"
            f"Detection threshold: pre-drift mean + {cfg.benchmark.threshold_sigmas} sigma "
            f"(held-out pre-drift windows only); persistence "
            f"{cfg.benchmark.detection_persistence} consecutive windows.\n"
            f"Deployed quantum feature map (frozen before evaluation): "
            f"{cfg.quantum_kernel.feature_map}\n\n"
            "Generated by benchmark/export_pdf.py from results.csv, "
            "ablation_results.csv and INTERPRETATION.md.",
            font_size=10,
        )

        table_columns = [
            "scenario", "kind", "detector", "detected", "delay",
            "false_alarm_rate", "separation",
        ]
        _table_page(
            pdf,
            "Detection performance — population view",
            results[results["subset"] == "population"][table_columns],
        )
        _table_page(
            pdf,
            "Detection performance — fraud-subset view",
            results[results["subset"] == "fraud"][table_columns],
            note="Windows below the minimum fraud-subset size are excluded (NaN-skipped).",
        )
        _table_page(
            pdf,
            "Feature-map ablation (held-out scenarios only)",
            ablation,
            note="angle = no-entanglement control; selection frozen before evaluation.",
        )
        _table_page(
            pdf,
            "Compute cost — mean wall-clock ms per window",
            results[results["subset"] == "population"]
            .groupby("detector", as_index=False)["mean_wall_clock_ms"]
            .mean()
            .round(1)
            .sort_values("mean_wall_clock_ms"),
        )

        _text_page(pdf, "Interpretation", interpretation, font_size=9)

        plots_dir = BENCH_DIR / "plots"
        for scenario in cfg.benchmark.evaluation_scenarios:
            for subset in ("population", "fraud"):
                image_path = plots_dir / f"bench_{scenario}_{subset}.png"
                if image_path.exists():
                    _image_page(pdf, f"{scenario} — {subset}", image_path)

    print(f"wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
